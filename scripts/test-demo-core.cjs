const assert = require('node:assert/strict');
const D = require('./load-model.cjs')('lib');
assert.equal(D.mean([1,2,3]),2);
assert.equal(D.sd([1,2,3]),1);
assert.ok(Number.isNaN(D.sd([1])));
const fit=D.linearFit([0,1,2,3],[2,5,8,11]);
assert.equal(fit.a,2);assert.equal(fit.b,3);assert.equal(fit.s,0);assert.equal(fit.r2,1);
const noisy=D.linearFit([0,1,2,3],[2,5.2,7.8,11]);
assert.ok(noisy.s>0);assert.ok(noisy.residuals.some(x=>x<0)&&noisy.residuals.some(x=>x>0));
assert.throws(()=>D.linearFit([1,1],[2,3]));
assert.throws(()=>D.linearFit([0,1],[2]));
assert.throws(()=>D.linearFit([0,1],[2,Infinity]));
const first=D.rng(207),second=D.rng(207),third=D.rng(208);
const xs=Array.from({length:2000},()=>first()),ys=Array.from({length:2000},()=>second());
assert.deepEqual(xs,ys);assert.notEqual(xs[0],third());
assert.ok(xs.every(x=>x>=0&&x<1));
const random=D.rng(71),normal=Array.from({length:10000},()=>D.normal(random));
assert.ok(Math.abs(D.mean(normal))<.04);assert.ok(Math.abs(D.sd(normal)-1)<.04);
assert.equal(D.clamp(-2,0,10),0);assert.equal(D.clamp(12,0,10),10);
assert.equal(D.fmt(NaN),'not available');
console.log('PASS: shared line fitting, numerical guards, deterministic sampling and normal generator');
